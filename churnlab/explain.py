"""SHAP explanations for the XGBoost churn pipeline.

`shap_by_feature` uses XGBoost's built-in TreeSHAP (pred_contribs), so the
API can explain predictions without the shap package installed. One-hot
columns are summed back to their source feature ("Contract" rather than
"Contract_Month-to-month"); SHAP values are additive, so the sum is exact.

Run: python -m churnlab.explain   (writes docs/shap_summary.png and
docs/customer-explanations.md)
"""

from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.pipeline import Pipeline

from churnlab.data import CATEGORICAL, FEATURES, NUMERIC, cohort_split, load

DOCS = Path("docs")


def _source_feature(name: str) -> str:
    """Map a transformed column name back to the raw feature it came from."""
    kind, rest = name.split("__", 1)  # "num__tenure", "cat__Contract_Two year"
    if kind == "num":
        return rest
    return next(c for c in CATEGORICAL if rest.startswith(c + "_"))


def shap_by_feature(model: Pipeline, X: pd.DataFrame) -> tuple[pd.DataFrame, np.ndarray]:
    """Return (per-feature SHAP values in log-odds, base values), one row per customer."""
    pre, clf = model.named_steps["pre"], model.named_steps["clf"]
    Xt = pre.transform(X[FEATURES])
    contribs = clf.get_booster().predict(xgb.DMatrix(Xt), pred_contribs=True)
    source = [_source_feature(n) for n in pre.get_feature_names_out()]
    per_col = pd.DataFrame(contribs[:, :-1], columns=source, index=X.index)
    grouped = per_col.T.groupby(level=0).sum().T[NUMERIC + CATEGORICAL]
    return grouped, contribs[:, -1]


def top_drivers(model: Pipeline, row: pd.DataFrame, k: int = 3) -> list[dict]:
    """Top-k features by |SHAP| for one customer, with direction."""
    values, _ = shap_by_feature(model, row)
    s = values.iloc[0]
    top = s.reindex(s.abs().sort_values(ascending=False).index)[:k]
    return [
        {
            "feature": f,
            "value": str(row.iloc[0][f]),
            "shap": round(float(v), 4),
            "direction": "raises churn risk" if v > 0 else "lowers churn risk",
        }
        for f, v in top.items()
    ]


def summary_plot(values: pd.DataFrame, X: pd.DataFrame, title: str, path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import shap  # lab-only dependency

    shown = X[values.columns].apply(
        lambda c: c if pd.api.types.is_numeric_dtype(c) else c.astype("category").cat.codes
    )
    shap.summary_plot(values.to_numpy(), shown, show=False, max_display=12)
    plt.title(title)
    plt.tight_layout()
    plt.savefig(path, dpi=120)
    plt.close()


def customer_report(model: Pipeline, X: pd.DataFrame) -> str:
    """Markdown with three customers: highest, median and lowest predicted risk."""
    p = model.predict_proba(X[FEATURES])[:, 1]
    order = np.argsort(p)
    picks = {
        "Highest risk": order[-1],
        "Median risk": order[len(order) // 2],
        "Lowest risk": order[0],
    }
    lines = [
        "# Per-customer SHAP explanations",
        "",
        "Generated by `python -m churnlab.explain` from the XGBoost churn model on the",
        "newest-cohort test set (tenure < 12 months). SHAP values are in log-odds: positive",
        "pushes the prediction toward churn, negative away from it.",
        "",
    ]
    for label, i in picks.items():
        row = X.iloc[[i]]
        lines += [
            f"## {label}: predicted churn probability {p[i]:.1%}",
            "",
            "| feature | value | SHAP | effect |",
            "|---|---|---|---|",
        ]
        for d in top_drivers(model, row, k=5):
            lines.append(f"| {d['feature']} | {d['value']} | {d['shap']:+.3f} | {d['direction']} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    from churnlab.train import MODEL_DIR

    model = joblib.load(MODEL_DIR / "churn_xgb.joblib")
    _, test = cohort_split(load())
    DOCS.mkdir(exist_ok=True)
    values, _ = shap_by_feature(model, test)
    title = "SHAP summary: XGBoost churn model, newest cohort"
    summary_plot(values, test, title, DOCS / "shap_summary.png")
    (DOCS / "customer-explanations.md").write_text(customer_report(model, test))
    print("wrote docs/shap_summary.png and docs/customer-explanations.md")


if __name__ == "__main__":
    main()
