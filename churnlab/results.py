"""Build RESULTS.md from the metrics files the pipeline writes.

Every number here comes from reports/metrics/*.json or a pytest count, and
each row names the command that produced it.

Run: python -m churnlab.results
"""

import json
import math
import re
import subprocess
import sys
from pathlib import Path

from abtest.power import sample_size_proportions
from abtest.sequential import peeking_false_positive_rate

M = Path("reports/metrics")


def count_tests(path: str = "tests") -> int:
    out = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", path],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return int(re.search(r"(\d+) tests? collected", out).group(1))


def build() -> str:
    churn = json.loads((M / "churn.json").read_text())
    up = json.loads((M / "uplift.json").read_text())
    c, r = churn["cohort"], churn["random"]
    train_cmd, up_cmd = "`python -m churnlab.train`", "`python -m churnlab.uplift`"

    rows = [
        "# Results",
        "",
        "Generated by `python -m churnlab.results`. Re-run `scripts/check.sh` to reproduce.",
        "",
        "## Churn model (7,043 Telco customers)",
        "",
        f"Test set = newest signup cohort (tenure < 12 months, n={c['n_test']}, "
        f"churn rate {c['xgboost']['base_rate']:.1%}); train n={c['n_train']}.",
        "",
        "| Split | Model | AUC-PR | AUC-ROC | Top-decile lift | Brier | Command |",
        "|---|---|---|---|---|---|---|",
    ]
    for split, d in (("cohort (leakage-safe)", c), ("random (for comparison)", r)):
        for name in ("logistic", "xgboost"):
            m = d[name]
            rows.append(
                f"| {split} | {name} | {m['auc_pr']:.3f} | {m['auc_roc']:.3f} | "
                f"{m['top_decile_lift']:.2f}x | {m['brier']:.3f} | {train_cmd} |"
            )
    rows += [
        "",
        f"Top-decile lift on the cohort split is capped at {1 / c['xgboost']['base_rate']:.2f}x "
        "because about half of the newest cohort churns.",
        "",
        "## Uplift models (simulated retention offer, held-out 30%)",
        "",
        f"Test n={up['n_test']}; true average effect {up['true_ate_test']:.3f}; "
        f"best possible mean uplift in the top 20% (oracle) {up['oracle_top20_true_uplift']:.3f}.",
        "",
        "| Targeting | Qini (norm.) | AUUC (norm.) | Mean true uplift, top 20% | "
        "Share of oracle | Command |",
        "|---|---|---|---|---|---|",
    ]
    labels = {
        "uplift_forest": "Uplift random forest",
        "t_learner": "T-learner (2x XGBoost)",
        "churn_risk": "Churn risk (no uplift model)",
        "random": "Random",
    }
    for key, label in labels.items():
        m = up[key]
        q = f"{m['qini']:.3f}" if "qini" in m else "-"
        a = f"{m['auuc']:.3f}" if "auuc" in m else "-"
        rows.append(
            f"| {label} | {q} | {a} | {m['top20_true_uplift']:.3f} | "
            f"{m['top20_share_of_oracle']:.1%} | {up_cmd} |"
        )
    budgets = list(up["uplift_forest"]["retained_by_budget"])
    rows += [
        "",
        "### Expected customers retained by offer budget (of 7,043 customers)",
        "",
        "| Targeting | " + " | ".join(f"offers to {b}" for b in budgets) + " | Command |",
        "|---|" + "---|" * len(budgets) + "---|",
    ]
    for key, label in labels.items():
        vals = up[key]["retained_by_budget"]
        cells = " | ".join(f"{vals[b]:.0f}" for b in budgets)
        rows.append(f"| {label} | {cells} | {up_cmd} |")
    rows += [
        "",
        "## A/B testing toolkit and tests",
        "",
        "| What | Value | Command |",
        "|---|---|---|",
        "| Customers per arm to detect churn 26.5% -> 23.5% (alpha .05, power .8) | "
        f"{math.ceil(sample_size_proportions(0.265, 0.235)):,} | `python -m churnlab.results` |",
        "| False-positive rate when an A/A test is checked at 10 looks (nominal 5%) | "
        f"{peeking_false_positive_rate(10):.1%} | `python -m churnlab.results` |",
        "| Known-result unit tests (Cohen, statsmodels, scipy, Armitage) | "
        f"{count_tests('tests/test_abtest.py')} | `pytest tests/test_abtest.py` |",
        f"| API tests | {count_tests('tests/test_api.py')} | `pytest tests/test_api.py` |",
        f"| All tests | {count_tests()} | `pytest` |",
        "",
    ]
    return "\n".join(rows)


if __name__ == "__main__":
    text = build()
    Path("RESULTS.md").write_text(text)
    print(text)
